import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..")
const outputPath = join(
  projectRoot,
  "registry/default/minim-icons/minim-icons.tsx"
)

const icons = [
  ["minim-1", "minim1.svg", "minim1 selected.svg"],
  ["minim-2", "minim2.svg", "minim2 selected.svg"],
  ["minim-3", "minim3.svg", "minim3 selected.svg"],
  ["minim-4", "minim4.svg", "minim4 selected.svg"],
  ["minim-5", "minim5 .svg", "minim5 selected.svg"],
  ["minim-6", "minim6.svg", "minim6 selected.svg"],
  ["library", "Library.svg", "Library Selected.svg"],
  ["catalog", "Catalog.svg", "Catalog Selected.svg"],
  ["search", "Search.svg", "Search Selected.svg"],
  ["explore", "explore.svg", "explore selected.svg"],
  ["explore-2", "explore2.svg", "explore2 selected.svg"],
  ["notification", "Notification.svg", "Notification Selected.svg"],
  ["profile", "Profile.svg", "Profile Selected.svg"],
  ["profile-2", "Profile2.svg", "Profile2 Selected.svg"],
  ["settings", "Settings.svg", "Settings Selected.svg"],
  ["settings-2", "Settings2.svg", "Settings2 Selected.svg"],
  ["left", "left.svg", "left selected.svg"],
  ["right", "right.svg", "right selected.svg"],
  ["up", "up.svg", "up selected.svg"],
  ["down", "down .svg", null],
]

function inlineClassStyles(svg) {
  const classStyles = new Map()

  for (const match of svg.matchAll(/\.(cls-[\w-]+)\s*\{([^}]+)\}/g)) {
    const declarations = match[2]
      .split(";")
      .map((declaration) => declaration.trim())
      .filter(Boolean)
      .map((declaration) => declaration.replace(/#000(?:000)?/gi, "currentColor"))
      .join(";")

    classStyles.set(match[1], declarations)
  }

  let result = svg.replace(/<defs>[\s\S]*?<\/defs>/g, "")

  for (const [className, declarations] of classStyles) {
    result = result.replaceAll(
      `class="${className}"`,
      `style="${declarations}"`
    )
  }

  return result
}

function readSvg(fileName) {
  const svg = inlineClassStyles(
    readFileSync(join(projectRoot, fileName), "utf8")
  )
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1]
  const body = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/)?.[1]

  if (!viewBox || body === undefined) {
    throw new Error(`Could not parse ${fileName}`)
  }

  return {
    viewBox,
    body: body.trim().replace(/#000(?:000)?/gi, "currentColor"),
  }
}

const source = new Map()

for (const [name, defaultFile, selectedFile] of icons) {
  const defaultIcon = readSvg(defaultFile)
  const selectedIcon = selectedFile
    ? readSvg(selectedFile)
    : {
        viewBox: defaultIcon.viewBox,
        body: `<rect width="24" height="24" rx="6" ry="6"/><g fill="#fff">${defaultIcon.body}</g>`,
      }

  if (defaultIcon.viewBox !== selectedIcon.viewBox) {
    throw new Error(`Variant viewBox mismatch for ${name}`)
  }

  source.set(name, {
    viewBox: defaultIcon.viewBox,
    default: defaultIcon.body,
    selected: selectedIcon.body,
  })
}

const names = icons.map(([name]) => `  ${JSON.stringify(name)},`).join("\n")
const records = [...source]
  .map(
    ([name, icon]) => `  ${JSON.stringify(name)}: {
    viewBox: ${JSON.stringify(icon.viewBox)},
    default: ${JSON.stringify(icon.default)},
    selected: ${JSON.stringify(icon.selected)},
  },`
  )
  .join("\n")

const output = `// This file is generated by scripts/build-minim-icons.mjs.
// Edit the source SVG files or generator, then run npm run icons:build.

import * as React from "react"

export const iconNames = [
${names}
] as const

export type IconName = (typeof iconNames)[number]
export type IconVariant = "default" | "selected"

const icons = {
${records}
} as const satisfies Record<
  IconName,
  { viewBox: string; default: string; selected: string }
>

export interface MinimIconProps
  extends Omit<React.ComponentPropsWithoutRef<"svg">, "children"> {
  name: IconName
  variant?: IconVariant
  title?: string
}

export const MinimIcon = React.forwardRef<SVGSVGElement, MinimIconProps>(
  function MinimIcon(
    { name, variant = "default", title, width = "1em", height = "1em", ...props },
    ref
  ) {
    const icon = icons[name]

    return (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        viewBox={icon.viewBox}
        width={width}
        height={height}
        fill="currentColor"
        role={title ? "img" : undefined}
        aria-hidden={title ? undefined : true}
        focusable="false"
        {...props}
      >
        {title ? <title>{title}</title> : null}
        <g dangerouslySetInnerHTML={{ __html: icon[variant] }} />
      </svg>
    )
  }
)
`

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, output)

console.log(`Built ${source.size} icons at ${outputPath}`)
