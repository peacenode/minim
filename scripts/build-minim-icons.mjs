import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { iconSources } from "./icon-sources.mjs"

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..")
const outputDir = join(projectRoot, "registry/default/minim-icons")

function componentName(name) {
  return `${name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")}Icon`
}

function jsxAttributeName(name) {
  return name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())
}

function inlineClassAttributes(svg) {
  const classAttributes = new Map()

  for (const match of svg.matchAll(/\.(cls-[\w-]+)\s*\{([^}]+)\}/g)) {
    const attributes = match[2]
      .split(";")
      .map((declaration) => declaration.trim())
      .filter(Boolean)
      .map((declaration) => {
        const separator = declaration.indexOf(":")
        const property = jsxAttributeName(declaration.slice(0, separator).trim())
        const value = declaration
          .slice(separator + 1)
          .trim()
          .replace(/#000(?:000)?/gi, "currentColor")

        return `${property}=${JSON.stringify(value)}`
      })
      .join(" ")

    classAttributes.set(match[1], attributes)
  }

  let result = svg.replace(/<defs>[\s\S]*?<\/defs>/g, "")

  for (const [className, attributes] of classAttributes) {
    result = result.replaceAll(`class="${className}"`, attributes)
  }

  return result
}

function readSvg(fileName) {
  const svg = inlineClassAttributes(
    readFileSync(join(projectRoot, fileName), "utf8")
  )
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1]
  const body = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/)?.[1]

  if (!viewBox || body === undefined) {
    throw new Error(`Could not parse ${fileName}`)
  }

  return {
    viewBox,
    body: body.trim().replace(/#000(?:000)?/gi, "currentColor"),
  }
}

function indent(value, spaces) {
  const padding = " ".repeat(spaces)
  return value
    .split("\n")
    .map((line) => `${padding}${line}`)
    .join("\n")
}

function componentSource(name, icon) {
  const component = componentName(name)

  return `// This file is generated by scripts/build-minim-icons.mjs.
// Edit the source SVG files or generator, then run npm run icons:build.

import * as React from "react"

export interface ${component}Props
  extends Omit<React.ComponentPropsWithoutRef<"svg">, "children"> {
  variant?: "default" | "selected"
  title?: string
}

export const ${component} = React.forwardRef<SVGSVGElement, ${component}Props>(
  function ${component}(
    { variant = "default", title, width = "1em", height = "1em", ...props },
    ref
  ) {
    return (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        viewBox=${JSON.stringify(icon.viewBox)}
        width={width}
        height={height}
        fill="currentColor"
        role={title ? "img" : undefined}
        aria-hidden={title ? undefined : true}
        focusable="false"
        {...props}
      >
        {title ? <title>{title}</title> : null}
        {variant === "selected" ? (
          <>
${indent(icon.selected, 12)}
          </>
        ) : (
          <>
${indent(icon.default, 12)}
          </>
        )}
      </svg>
    )
  }
)
`
}

const source = new Map()

for (const [name, defaultFile, selectedFile] of iconSources) {
  const defaultIcon = readSvg(defaultFile)
  const selectedIcon = selectedFile
    ? readSvg(selectedFile)
    : {
        viewBox: defaultIcon.viewBox,
        body: `<rect width="24" height="24" rx="6" ry="6"/><g fill="#fff">${defaultIcon.body}</g>`,
      }

  if (defaultIcon.viewBox !== selectedIcon.viewBox) {
    throw new Error(`Variant viewBox mismatch for ${name}`)
  }

  source.set(name, {
    viewBox: defaultIcon.viewBox,
    default: defaultIcon.body,
    selected: selectedIcon.body,
  })
}

rmSync(outputDir, { recursive: true, force: true })
mkdirSync(outputDir, { recursive: true })

for (const [name, icon] of source) {
  writeFileSync(
    join(outputDir, `${name}-icon.tsx`),
    componentSource(name, icon)
  )
}

const imports = [...source]
  .map(
    ([name]) =>
      `import { ${componentName(name)} } from "@/registry/default/minim-icons/${name}-icon"`
  )
  .join("\n")
const exports = [...source]
  .map(([name]) => `  ${componentName(name)},`)
  .join("\n")
const names = [...source]
  .map(([name]) => `  ${JSON.stringify(name)},`)
  .join("\n")
const componentMap = [...source]
  .map(([name]) => `  ${JSON.stringify(name)}: ${componentName(name)},`)
  .join("\n")

const indexSource = `// This file is generated by scripts/build-minim-icons.mjs.
// Edit the source SVG files or generator, then run npm run icons:build.

import * as React from "react"

${imports}

export {
${exports}
}

export const iconNames = [
${names}
] as const

export type IconName = (typeof iconNames)[number]
export type IconVariant = "default" | "selected"

const iconComponents = {
${componentMap}
} as const

export interface MinimIconProps
  extends Omit<React.ComponentPropsWithoutRef<"svg">, "children"> {
  name: IconName
  variant?: IconVariant
  title?: string
}

export const MinimIcon = React.forwardRef<SVGSVGElement, MinimIconProps>(
  function MinimIcon({ name, variant = "default", ...props }, ref) {
    const Icon = iconComponents[name]

    return <Icon ref={ref} variant={variant} {...props} />
  }
)
`

writeFileSync(join(outputDir, "minim-icons.tsx"), indexSource)

const registryFiles = [...source].map(([name]) => ({
  path: `registry/default/minim-icons/${name}-icon.tsx`,
  type: "registry:component",
  target: `@components/minim-icons/${name}-icon.tsx`,
}))
const registryItems = [
  {
    name: "minim-icons",
    type: "registry:component",
    title: "Minim Icons",
    description: `${source.size} customizable Minim interface icons with default and selected variants.`,
    author: "Minim",
    files: [
      ...registryFiles,
      {
        path: "registry/default/minim-icons/minim-icons.tsx",
        type: "registry:component",
        target: "@components/minim-icons/minim-icons.tsx",
      },
    ],
    docs: "Import any named icon component, or use MinimIcon with a name. Pass variant=\"selected\" for its selected artwork and customize it with standard SVG props or Tailwind classes.",
  },
  ...[...source].map(([name]) => {
    const component = componentName(name)
    const title = component
      .replace(/Icon$/, "")
      .replace(/([a-z])([A-Z0-9])/g, "$1 $2")

    return {
      name,
      type: "registry:component",
      title,
      description: `${title} with default and selected variants.`,
      author: "Minim",
      files: [registryFiles.find((file) => file.path.includes(`/${name}-icon.tsx`))],
      docs: `Import ${component} from \"@/components/minim-icons/${name}-icon\". Pass variant=\"selected\" for its selected artwork.`,
    }
  }),
]

writeFileSync(
  join(projectRoot, "registry.json"),
  `${JSON.stringify(
    {
      $schema: "https://ui.shadcn.com/schema/registry.json",
      name: "minim",
      homepage: "https://minim.peaceno.de",
      items: registryItems,
    },
    null,
    2
  )}\n`
)

console.log(`Built ${source.size} icon components at ${outputDir}`)
